function 判断_猫卡数量()
	local 滑动次数 = 0
	
	:: 猫卡数量标签 ::
	
	-- OCR识别数量的内部函数
	local function 数量(x1 , y1 , x2 , y2)
		setDict(0 , "数字字库.txt")
		useDict(0)
		local str = ocr(x1 , y1 , x2 , y2 , "ffffff-303030" , 0.8 , 1 , 1)
		if str ~= nil and str ~= "" then
			print('OCR识别到数量: ' .. str)
			return str
		end
		return nil
	end
	
	-- 先识别猫卡位置
	local ret , x , y = findPic(184 , 138 , 606 , 636 , "猫卡.png" , "202020" , 0 , 0.85)
	if x == - 1 or y == - 1 then
		显示('未识别到猫卡图标')
		return nil , false -- 返回: 数量=nil, 是否找到猫卡=false
	end
	
	print('识别到猫卡位置: (' .. x .. ', ' .. y .. ')')
	
	-- 根据猫卡位置动态计算识别数量的范围
	-- 基于猫卡位置加上相对偏移量
	-- 参考: 猫卡(391,354)->识别(359,374,432,398)  猫卡(219,424)->识别(187,444,258,468)
	local ocr_x1 = x - 32 -- 左偏移
	local ocr_y1 = y + 20 -- 上偏移
	local ocr_x2 = x + 41 -- 右偏移
	local ocr_y2 = y + 44 -- 下偏移
	
	print('识别数量范围: (' .. ocr_x1 .. ', ' .. ocr_y1 .. ', ' .. ocr_x2 .. ', ' .. ocr_y2 .. ')')
	
	-- 识别该位置的猫卡数量
	local num = 数量(ocr_x1 , ocr_y1 , ocr_x2 , ocr_y2)
	
	if num then
		print('成功识别到猫卡数量: ' .. num)
		return num , true -- 返回: 数量=字符串, 是否找到猫卡=true
	else
		-- 识别到猫卡但没识别到数量，说明数量被遮挡了，小幅度向上滑动调整
		if 滑动次数 < 2 then
			显示('数量被遮挡 (' .. (滑动次数 + 1) .. '/2)')
			滑动(437 , 407 , 439 , 350 , 2 , 2 , {15 , 35} , {900 , 1200} , {300 , 400})
			随机延时(500 , 700)
			滑动次数 = 滑动次数 + 1
			goto 猫卡数量标签
		else
			显示('微调2次后仍未识别到数量')
			return nil , true -- 返回: 数量=nil, 是否找到猫卡=true
		end
	end
end
function 功能_获取猫卡数量()
	
	初始化城镇界面()
	local 开始时间 = os.time()
	local 开始计时 = false
	local 滑动次数 = 0
	
	local 首次运行 = true
	while true do
		if not 首次运行 then
			随机延时(800 , 900)
		end
		首次运行 = false
		-- 检测游戏闪退
		if 快速检测游戏状态() then
			开始时间 = os.time()
		end
		
		-- 超时检测
		if 开始计时 then
			if os.time() - 开始时间 > 90 then
				显示('识别猫卡操作超时(90秒)，强制退出')
				清屏(true)
				return nil
			end
		end
		
		显示('识别猫卡数量运行中....')
		
		if 判断_城镇界面() then
			开始计时 = true
			按下点击({1193 , 632 , 1237 , 676})--背包
			随机延时(300 , 500)
			
		elseif 判断_打开背包界面() then
			
			if 入口_金库() then
				-- 继续执行，进入金库
				
			elseif 判断_冒险团金库() then
				-- 继续执行，在冒险团金库界面
				
			elseif 判断_选中冒险团金库() then
				-- 在冒险团金库中，开始识别猫卡数量
				local 识别结果 , 找到猫卡 = 判断_猫卡数量()
				
				if 识别结果 then
					-- 成功识别到数量
					print('成功获取猫卡数量: ' .. 识别结果)
					显示('猫卡数量: ' .. 识别结果)
					初始化城镇界面()
					return 识别结果
				elseif 找到猫卡 then
					-- 找到猫卡但数量识别失败（已经微调过了）
					滑动次数 = 滑动次数 + 1
					print('找到猫卡但数量识别失败，第 ' .. 滑动次数 .. ' 次尝试')
					
					if 滑动次数 >= 6 then
						显示('尝试6次后仍未识别到猫卡数量')
						初始化城镇界面()
						return nil
					else
						显示('小幅度滑动后重试 (' .. 滑动次数 .. '/6)')
						-- 小幅度滑动，避免把猫卡滑走
						滑动(435 , 572 , 439 , 480 , 3 , 3 , {15 , 30} , {800 , 1000} , {200 , 300})
						随机延时(500 , 800)
					end
				else
					-- 没找到猫卡图标
					滑动次数 = 滑动次数 + 1
					print('未找到猫卡，第 ' .. 滑动次数 .. ' 次尝试')
					
					if 判断_拓展冒险团金库() or 滑动次数 >= 6 then
						显示('6次后仍未找到猫卡')
						初始化城镇界面()
						return nil
					else
						显示('未识别到猫卡 (' .. 滑动次数 .. '/6)')
						-- 大幅度滑动寻找猫卡
						滑动(435 , 572 , 439 , 232 , 5 , 5 , {15 , 30} , {1000 , 1500} , {200 , 300})
						随机延时(500 , 800)
					end
				end
			end
			
		elseif 入口_确认() then
			-- 处理确认弹窗
			
		else
			-- 清屏处理其他界面
			清屏(true)
			随机延时(300 , 500)
		end
	end
	
end

