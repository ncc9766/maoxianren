-- 本地配置辅助函数
function 保存配置到本地(选中的配置名称 , 配置数据)
	print("=== 开始保存配置到本地 ===")
	print("配置名称:" , 选中的配置名称)
	print("配置数据类型:" , type(配置数据))
	
	local 目录路径 = getSdPath() .. "/用户配置/"
	--print("目录路径:" , 目录路径)
	
	local 文件路径 = 目录路径 .. 选中的配置名称 .. ".json"
	print("文件路径:" , 文件路径)
	
	-- 确保目录存在
	local 检查成功 , 检查结果 = pcall(function()
		return io.open(目录路径)
	end)
	
	--print("检查目录是否存在 - 成功:" , 检查成功 , "结果:" , 检查结果)
	
	if 检查成功 and not 检查结果 then
		print("目录不存在，创建目录")
		mkdir(目录路径)
	end
	
	-- 保存配置到本地文件
	print("开始编码JSON...")
	local 编码成功 , json字符串 = pcall(function()
		return jsonLib.encode(过滤保留字段(配置数据))
	end)
	
	if not 编码成功 then
		print("JSON编码失败:" , json字符串)
		return false
	end
	
	print("JSON编码成功，长度:" , string.len(json字符串))
	
	--print("开始写入文件...")
	local 写入成功 , 写入结果 = pcall(function()
		return writeFile(文件路径 , json字符串)
	end)
	
	--print("写入文件 - 成功:" , 写入成功 , "结果:" , 写入结果)
	
	local 成功 = 写入成功 and 写入结果
	
	if 成功 then
		toast("保存".."配置名称:"..选中的配置名称.."成功" , 0 , 0 , 12)
	else
		print("本地保存配置失败:" .. 文件路径)
	end
	print("=== 保存配置完成 ===")
	return 成功
end
function 从本地读取配置(选中的配置名称)
	local 文件路径 = getSdPath() .. "/用户配置/" .. 选中的配置名称 .. ".json"
	if io.open(文件路径) then
		local 内容 = readFile(文件路径)
		if 内容 then
			return jsonLib.decode(内容)
		end
	end
	return nil
end
function 删除本地配置(选中的配置名称)
	local 文件路径 = getSdPath() .. "/用户配置/" .. 选中的配置名称 .. ".json"
	local 文件 = io.open(文件路径 , "r")
	if not 文件 then
		print("删除失败：文件不存在 → " .. 文件路径)
		return false
	end
	文件:close() -- 先关掉打开的文件
	local 删除成功 , 错误信息 = os.remove(文件路径)
	if 删除成功 then
		print("删除成功：" .. 文件路径)
		return true
	else
		print("删除失败：" .. 错误信息)
		return false
	end
end
function 获取本地配置列表()
	local 目录路径 = getSdPath() .. "/用户配置/"
	local 列表 = {}
	if io.open(目录路径) then
		local 文件们 = listDir(目录路径)
		for i = 1 , #文件们 do
			local 文件名 = 文件们[i]
			if string.find(文件名 , "%.json$") then
				local 配置名称 = string.gsub(文件名 , "%.json$" , "")
				table.insert(列表 , 配置名称)
			end
		end
	end
	return 列表
end
