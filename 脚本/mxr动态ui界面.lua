-- 检查应用是否安装
function checkPackageExists()
	local installedApps = getInstalledApk()
	if installedApps then
		for _ , pkg in pairs(installedApps) do
			if pkg == TARGET_PACKAGE then
				return true
			end
		end
	end
	return false
end

-- 执行备份
function executeBackup(账号名称 , BACKUP_FILE , execFunc , strategyName)
	execFunc("mkdir -p '"..BACKUP_DIR.."'")
	local hudId = createHUD()
	showHUD(hudId , 账号名称.."备份中,请稍候..." , 20 , "0xffffffff" , "0xff000000" , 360 , 0 , 680 , 0 , 0)
	execFunc("tar -zcpf '"..BACKUP_FILE.."' --exclude='"..EXCLUDE_DOLPHIN.."' --exclude='"..EXCLUDE_GAMELET.."' --exclude='"..EXCLUDE_PUFFER.."' '"..DATA_PATH.."'")
	hideHUD(hudId)
	local file = io.open(BACKUP_FILE , "r")
	if file then
		local size = file:seek("end")
		file:close()
		if size > 0 then
			print("备份完成: "..BACKUP_FILE)
			toast("备份完成:文件大小: "..string.format("%.2f MB" , size / 1024 / 1024) , 0 , 0 , 20)
			return true
		else
			print("备份失败("..strategyName.."): 文件大小为0")
			return false
		end
	else
		print("备份失败("..strategyName.."): 文件不存在")
		toast("备份失败: 文件不存在" , 0 , 0 , 20)
		return false
	end
end

function 功能_备份账号()
	if not checkPackageExists() then
		print("需要备份的应用不存在")
		return
	end
	local 主界面UI参数 = ui.获取当前界面所有控件的值()
	local 账号索引 = 主界面UI参数.下拉框_备份_账号列表 or 0
	local 备份账号名称 = "账号"..(账号索引 + 1)
	
	local BACKUP_FILE = BACKUP_DIR.. "/"..备份账号名称.."备份.tar.gz"
	print("备份: "..BACKUP_FILE)
	
	print("\n开始备份到: "..备份账号名称 , 0 , 0 , 20)
	for i , strategy in ipairs(execStrategies) do
		if i > 1 then
			print("尝试备份方案"..i..": "..strategy.name , 0 , 0 , 20)
		end
		local success = executeBackup(备份账号名称 , BACKUP_FILE , strategy.execFunc , strategy.name)
		if success then
			sleep(100)
			return
		end
	end
	print("所有备份方案均失败")
	toast("备份失败")
	sleep(500)
end

function executeRestore(BACKUP_FILE , execFunc , strategyName)
	local hudId = createHUD()
	showHUD(hudId , "登录账号中,请稍候..." , 20 , "0xffffffff" , "0xff000000" , 360 , 0 , 680 , 0 , 0)
	local tarResult = execFunc("tar -zxf '"..BACKUP_FILE.."' -C /")
	-- 暂时注释掉restorecon命令，看是否因它导致问题
	-- local restoreResult = execFunc("restorecon -Rv '"..DATA_PATH.."'")
	hideHUD(hudId)
	print("tar返回值: "..tostring(tarResult))
	if tarResult == true or tarResult == 0 then -- 检查tar命令执行是否成功
		local testFile = io.open(DATA_PATH , "r")
		if testFile then
			testFile:close()
			print("登录账号("..strategyName..")")
			return true
		else
			print("登录账号("..strategyName.."): 验证失败，还原后文件不存在")
			return false
		end
	else
		print("登录账号("..strategyName.."): tar命令执行失败")
		return false
	end
end

