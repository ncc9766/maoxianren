-- 构建排除字段的快速查找表
function 构建排除集()
	
	local 集 = {}
	for _ , 字段名 in ipairs(需要保留的配置字段) do
		
		集[字段名] = true
	end
	return 集
end

-- 保存时：从配置数据中移除需要保留的字段，返回新表（不修改原表）
function 过滤保留字段(配置数据)
	local 排除集 = 构建排除集()
	local 结果 = {}
	for k , v in pairs(配置数据) do
		if not 排除集[k] then
			结果[k] = v
		end
	end
	return 结果
end
-- 从配置数据中提取需要保留的字段，返回新表
function 提取需要保留的字段(配置数据)
	local 结果 = {}
	for _ , 字段名 in ipairs(需要保留的配置字段) do
		if 配置数据[字段名] ~= nil then
			结果[字段名] = 配置数据[字段名]
		end
	end
	return 结果
end
-- 应用配置时：用当前界面值覆盖需要保留的字段
function 应用保留字段(目标配置 , 当前界面数据)
	for _ , 字段名 in ipairs(需要保留的配置字段) do
		
		if 当前界面数据[字段名] ~= nil then
			目标配置[字段名] = 当前界面数据[字段名]
		end
	end
	
end
