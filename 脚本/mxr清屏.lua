			print("清屏找到并处理：退出团本界面")
			
		elseif 清屏_点击关闭_伤害结算() then
			团本结束 = true
			总找到次数 = 总找到次数 + 1
			找到界面 = true
			print("清屏找到并处理：点击关闭")
		elseif 判断_返回战斗记录界面() then
			团本结束 = true
			总找到次数 = 总找到次数 + 1
			找到界面 = true
			print("清屏找到并处理：返回战斗记录界面")
		elseif 清屏_冒险团资产() then
			总找到次数 = 总找到次数 + 1
			找到界面 = true
			print("清屏找到并处理：冒险团资产")
			
		elseif 判断_分享_朋友圈() then
			
			按下点击({1204 , 661 , 1228 , 686}) --右下角X
			总找到次数 = 总找到次数 + 1
			找到界面 = true
			print("清屏找到并处理：冒险团资产")
			
		elseif 清屏_任务跳过() then
			总找到次数 = 总找到次数 + 1
			找到界面 = true
			显示("清屏找到并处理：跳过任务")
			
		elseif 判断_转职() then
			总找到次数 = 总找到次数 + 1
			找到界面 = true
			显示("清屏找到并处理：转职")
		elseif 判断_返回城镇_橘红色底部() then
			总找到次数 = 总找到次数 + 1
			找到界面 = true
			显示("清屏找到并处理：转职")
			
		elseif 清屏_广告() then
			总找到次数 = 总找到次数 + 1
			找到界面 = true
			print("找到并处理：广告")
			
		elseif 判断_分享装备() then
			总找到次数 = 总找到次数 + 1
			找到界面 = true
			print("找到并处理：分享装备")
			
		elseif 判断_帝国外围城墙() then
			总找到次数 = 总找到次数 + 1
			找到界面 = true
			print("找到并处理：帝国外围城墙")
			
		elseif 判断_洛兰_新手图指引图() and 判断_副本中() then
			
			自动刷图()
			找到界面 = true
			print("找到并处理：新手指引")
		end
		
		-- 如果是单次模式，处理完一次就退出
		if 单次模式 == true and 总找到次数 > 0 then
			break
		end
		
		-- 多次模式下，最多清理4个界面防止误识别陷入死循环
		if 单次模式 ~= true and 总找到次数 >= 2 then
			--print("已清理4个界面，退出防止死循环")
			break
		end
		
		-- 如果第一次就没找到任何界面，再查找一次后结束
		if 当前查找次数 == 1 and not 找到界面 then
			--print("第一次未找到界面，再查找一次")
			找到界面 = true -- 强制再查找一次
		elseif 单次模式 == true then
			-- 单次模式下，如果没找到界面就直接退出
			--print("未找到需要清理的任何界面")
			break
		end
		随机延时(50 , 100)
	end
	
	--显示("查找界面完成：总共查找"..总查找次数.."次，找到并关闭"..总找到次数.."个界面")
	
	-- 找到了返回 true，没找到返回 false
	if 总找到次数 > 0 then
		return true
	else
		return false
	end
end

