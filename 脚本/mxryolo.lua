	local 战斗中卡死开始时间 = nil -- 战斗状态下的卡死计时
	
	-- 被动技能检测相关变量
	local 被动技能列表 = {} -- 存储已发现的被动技能及其释放时间
	local 被动技能最小间隔 = 随机数(500 , 600) -- 被动技能释放间隔20-25秒
	local 被动技能距离阈值 = 40 -- 坐标相差80以上判断为不同被动技能
	
	-- 怪物等级颜色检测相关变量（链条对比模式）
	local 上次记录的颜色 = nil -- 上次记录的怪物等级颜色，形成A->B->新A->新B的链条
	local 上次对比时间 = 0 -- 上次对比颜色的时间戳
	local 颜色对比间隔 = 0.3 -- 对比间隔800毫秒
	
	-- =================================================================================
	-- 内部辅助函数定义
	-- =================================================================================
	
	-- @brief 安全地释放"自动打怪"状态
	local function 安全释放自动打怪()
		
		if 正在移动 then
			释放自动打怪()
			随机延时(100 , 150)
			正在移动 = false
		end
		
	end
	
	-- @brief 安全地启动"自动打怪"状态
	local function 安全启动自动打怪()
		随机延时(200 , 300)
		if not 正在移动 and 判断_副本中() then
			print('-----------------------不在移动并且在副本中启动自动打怪---------------------')
			
			自动打怪()
			正在移动 = true
		end
		
	end
	
	-- @brief 释放被动技能
	local function 释放被动技能(技能X , 技能Y)
		print("释放被动技能，坐标: (" .. 技能X .. ", " .. 技能Y .. ")")
		
		local 偏移X = math.random( - 10 , 10)
		local 偏移Y = math.random( - 10 , 10)
		local 实际X = 技能X + 偏移X
		local 实际Y = 技能Y + 偏移Y
		
		-- 按住技能中心点
		touchDown(0 , 实际X , 实际Y)
		随机延时(50 , 80) -- 短暂按住
		
		-- 向上快速拖动释放
		local 拖动距离 = math.random(300 , 400)
		local 目标Y = 实际Y - 拖动距离
		touchMove(0 , 实际X , 目标Y)
		随机延时(300 , 400) -- 拖动时间
		
		-- 释放
		touchUp(0)
		
		-- 添加防封随机偏移
		
	end
	
	-- @brief 检查被动技能是否需要释放
	local function 检查并释放被动技能(被动技能检测列表 , 当前时间 , 攻击中标签)
		if ( 被动技能检测列表 == nil or #被动技能检测列表 == 0 or 攻击中标签 ) and 判断_副本中() then
			return -- 没有被动技能或正在战斗中不释放
		end
		
		for _ , 被动技能 in ipairs(被动技能检测列表) do
			local 技能X = 被动技能.x
			local 技能Y = 被动技能.y
			
			-- 检查是否是新技能或需要释放
			local 需要释放 = false
			local 已存在技能 = nil
			
			-- 查找是否已存在相似位置的技能
			for i , 已记录技能 in ipairs(被动技能列表) do
				local 距离 = math.sqrt((技能X - 已记录技能.x)^2 + (技能Y - 已记录技能.y)^2)
				if 距离 < 被动技能距离阈值 then
					已存在技能 = 已记录技能
					已存在技能.index = i
					break
				end
			end
			
			if 已存在技能 then
				-- 已存在的技能，检查是否到了释放时间
				if 当前时间 - 已存在技能.上次释放时间 >= 被动技能最小间隔 then
					需要释放 = true
				end
			else
				-- 新发现的技能，直接释放
				需要释放 = true
				table.insert(被动技能列表 , {
					x = 技能X ,
					y = 技能Y ,
					上次释放时间 = 当前时间
				})
			end
			
			if 需要释放 then
				-- 释放被动技能前先安全释放自动打怪
				安全释放自动打怪()
				随机延时(500 , 700)
				释放被动技能(技能X , 技能Y)
				随机延时(200 , 250)
				-- 释放被动技能后立即启动自动打怪
				--自动打怪()
				安全启动自动打怪()
				-- 更新释放时间
				if 已存在技能 then
					被动技能列表[已存在技能.index].上次释放时间 = 当前时间
				end
			end
		end
	end
	
	-- =================================================================================
	-- 主逻辑开始
	-- =================================================================================
	--战斗前准备
	--技能8()
	if 判断_容颜洞穴() then
		
	elseif 判断_浅溪之地() then
		
	elseif 判断_绿都 () then
		
	end
	
