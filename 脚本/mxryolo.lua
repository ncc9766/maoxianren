							print("非战斗状态：人物卡住超过3秒，尝试随机移动或拖动轮盘")
							
							安全释放自动打怪()
							随机移动或拖动轮盘()
							安全启动自动打怪()
							上次对比时间 = 当前时间
						elseif 非战斗卡住时间 >= 0.7 then
							print("非战斗状态：人物卡住超过1秒，尝试重新启动自动打怪")
							
