							if not 突破峡谷() then
								释放检测到的技能(技能列表)
							end
							
							战斗开始时间 = os.time()
							扫屏寻怪()
							安全启动自动打怪()
							上次对比时间 = 当前时间
							非战斗卡死开始时间 = nil -- 重置计时器
							战斗中卡死开始时间 = nil
							未识别到怪物等级 = os.time()
							goto continue
							
						elseif 非战斗卡住时间 > 0.7 then
							
							if not 已启动 and not 判断_已启动自动() and 判断_副本中() then
								print("非战斗状态：人物卡住超过1秒，尝试重新启动自动打怪")
								安全释放自动打怪()
								安全启动自动打怪()
								goto continue
							end
							
						end
					else -- 战斗状态的卡死处理
						-- 检测到非战斗状态转换，重置非战斗卡死计时器
						if 非战斗卡死开始时间 ~= nil then
							print("从非战斗状态转为战斗状态，重置非战斗卡死计时器")
							非战斗卡死开始时间 = nil
						end
						
						非战斗卡死开始时间 = nil -- 重置计时器
						
					end
				else
					-- 角色在移动，重置所有卡住计时器
					print('人物正在移动，重置所有未移动计时')
					
					非战斗卡死开始时间 = nil
					上次人物检测时间 = os.time()
					上次找到人物时间 = os.time()
					上次人物坐标 = 人物位置
					位置有变化 = true
				end
				
			end
		else
			位置有变化 = false
			
		end
		if os.time() - 未识别到怪物等级 > 10 then
			
			if not 判断_怪物等级() then
				print('未识别到怪物等级超过10秒')
				安全释放自动打怪()
				if not 突破峡谷() then
					释放检测到的技能(技能列表)
				end
				
				战斗开始时间 = os.time()
				扫屏寻怪()
				
				安全启动自动打怪()
				非战斗卡死开始时间 = nil
				战斗中卡死开始时间 = nil
				上次找到人物时间 = os.time()
				上次人物检测时间 = os.time()
				未识别到怪物等级 = os.time()
			end
			
		end
		---------------------------------
		-- 4. 战斗决策逻辑
		---------------------------------
		
		---------------------------------------------------------------------------------------------------------
		
		----------------------------------------------------------------------------------------------------------
		
		if 怪物存在 and 找到人物 and not 移动标签 then
			local 目标怪物 = 怪物列表[1]
			local 距离 = math.sqrt((人物位置.x - 目标怪物.x)^2 + (人物位置.y - 目标怪物.y)^2)
			
			if 距离 <= 150 then -- 在攻击范围内 350
				print("进入攻击范围，准备攻击。")
				-- 计算怪物相对于人物的位置
				local 怪物在右边 = 目标怪物.x > 人物位置.x
				local 人物朝向 = 人物位置.朝向 or "未知"
				
				print(string.format("怪物位置: %s, 人物朝向: %s" , 怪物在右边 and "右边" or "左边" , 人物朝向))
				
				-- 根据朝向和怪物位置决策攻击方式
				if 怪物在右边 and 人物朝向 == "人物向右" then
					-- 怪物在右边且人物朝向右边，直接攻击
					if 判断_副本中() then
						print("怪物在右边且人物朝向正确，直接释放技能")
						if 技能列表 and #技能列表 > 0 then
							安全释放自动打怪()
							释放检测到的技能(技能列表)
						else
							print("无技能可用，继续攻击。")
						end
					end
					
				elseif 怪物在右边 and 人物朝向 == "人物向左" then
					-- 怪物在右边但人物朝向左边，需要调整方向
					
					print("怪物在右边但人物朝向错误，先调整方向")
					
					-- 调整方向后释放技能
					if 技能列表 and #技能列表 > 0 then
						安全释放自动打怪()
						调整方向向右()
						释放检测到的技能(技能列表)
					end
					安全启动自动打怪()
					
				elseif not 怪物在右边 and 人物朝向 == "人物向左" then
					-- 怪物在左边且人物朝向左边，直接攻击
					
					print("怪物在左边且人物朝向正确，直接释放技能")
					if 技能列表 and #技能列表 > 0 then
						安全释放自动打怪()
						释放检测到的技能(技能列表)
					else
						print("无技能可用，继续攻击。")
					end
					
				elseif not 怪物在右边 and 人物朝向 == "人物向右" then
					print("怪物在左边但人物朝向错误，先调整方向")
					if 技能列表 and #技能列表 > 0 then
						安全释放自动打怪()
						调整方向向左()
						释放检测到的技能(技能列表)
					end
					
					安全启动自动打怪()
				else
					-- 人物朝向检测失败，使用默认攻击方式
					
					print("人物朝向检测失败，使用默认攻击方式")
					if 技能列表 and #技能列表 > 0 then
						安全释放自动打怪()
						释放检测到的技能(技能列表)
					else
						print("无技能可用，继续攻击。")
					end
					安全启动自动打怪()
				end
				
			else
				
				安全启动自动打怪()
				正在移动 = true
			end
			
		else
			-- 没有怪物，继续移动探索
			if not 正在移动 then
				安全启动自动打怪()
				正在移动 = true
			end
		end
		
		if not 已启动 and not 判断_已启动自动() and 判断_副本中() then --and not 位置有变化
			
			安全释放自动打怪()
			安全启动自动打怪()
			
		end
		
		::continue::
		-- 清理截图
		if 截图 ~= nil and 截图.isRecycled() == false then
			截图.recycle()
		end
		随机延时(150 , 220) -- 主战斗循环间隔
	end
	安全释放自动打怪()
	
	releaseCapture()
end
