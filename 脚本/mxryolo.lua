						if 战斗卡住时间 >= 0.7 then
							print("战斗状态：人物卡住超过1秒，尝试重新启动自动打怪")
							安全释放自动打怪()
							安全启动自动打怪()
							上次找到人物时间 = os.time() -- 重置计时器
							战斗中卡死开始时间 = nil -- 重置计时器
							
						end
					end
				else
					-- 角色在移动，重置所有卡住计时器
					print('人物正在移动，重置所有未移动计时')
					非战斗卡死开始时间 = nil
					战斗中卡死开始时间 = nil
					上次人物检测时间 = os.time()
					上次找到人物时间 = os.time()
					上次人物坐标 = 人物位置
					位置有变化 = true
				end
			end
			
		else -- 如果没有找到人物
			位置有变化 = false
			if 当前在战斗 then
				
				if os.time() - 上次找到人物时间 >= 随机数(2 , 2.5) then
					print("超过1秒未检测到人物。")
					if 判断_副本中() then
						
						安全释放自动打怪()
						安全启动自动打怪()
						--随机延时(1000 , 1200)
						非战斗卡死开始时间 = nil
						非战斗卡死开始时间 = nil
						战斗中卡死开始时间 = nil
					end
