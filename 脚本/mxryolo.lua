		-- 1. 通用高优先级检查
		---------------------------------
		if 检测游戏是否闪退() then
			安全释放自动打怪()
			print("检测到游戏闪退，结束自动刷图。")
			return
			
		end
		if 判断_帝国外围城墙() then
			安全释放自动打怪()
			return
		end
		if 判断_提示_复活() then
			print("检测到复活弹窗，暂停攻击以处理。")
			安全释放自动打怪()
			随机延时(500 , 800)
			if 判断_没有复活币() then
				随机延时(300 , 500)
				if 判断_返回城镇_复活() then
					随机延时(400 , 500)
					发送喵提醒_自定义('没复活币返回城镇,请及时上线查看')
					随机延时(800 , 1000)
					入口_确认()
