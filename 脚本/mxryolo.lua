local function Match(obj , className)
	local info = {}
	info.x1 = obj[0]
	info.y1 = obj[1]
	info.x2 = obj[2]
	info.y2 = obj[3]
	info.prob = obj[4]
	info.label = className[obj[5] + 1]
	return info
end

local function BoxArr(obj , className)
	local arr = {}
	if obj ~= nil then
		local size = Array.getLength(obj)
		for i = 1 , size do
			arr[i] = Match(obj[i - 1] , className)
		end
	else
		return nil
	end
	return arr
end
