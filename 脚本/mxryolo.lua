function 移动到目标点()
	-- 目标点参数
	local 目标点X = 774
	local 目标点Y = 589
	local 距离目标 = 10 -- 距离目标点多近算作"到达"
	local 最大移动时间 = 2 -- 2秒
	local 开始时间 = os.time()
	local 当前拖动状态 = false -- 记录是否正在拖动
	
	while os.time() - 开始时间 < 最大移动时间 do
		local 截图 = LuaEngine.snapShot(0 , 0 , 0 , 0)
		local 检测结果 = Yolov8_640.detect(截图 , 0.45)
		
		if 检测结果 ~= nil then
			local 解析结果 = 检测结果 -- YOLOv11直接返回表格
			local 技能数量 = 0
			local 对象信息 = ""
			local 人物坐标X , 人物坐标Y = nil , nil
			
			for 索引 = 1 , #解析结果 do
				
				local 标签 = 解析结果[索引].label or "未知" -- YOLOv11直接返回标签字符串
				local 置信度 = string.format("%.2f" , 解析结果[索引].prob)
				
				if 标签 == "人物向左" or 标签 == "人物向右" then
					-- 底线中间点：(x1+x2)/2, y2
					横坐标 = math.floor((解析结果[索引].x1 + 解析结果[索引].x2) / 2)
					纵坐标 = math.floor(解析结果[索引].y2)
					人物坐标X = 横坐标
					人物坐标Y = 纵坐标
					对象信息 = "人物: " .. 横坐标 .. " " .. 纵坐标 .. ", " .. 置信度
					
				end
				
			end
			
			if 对象信息 ~= "" then
				print(对象信息)
			end
			
			-- 如果检测到人物，计算移动方向
			if 人物坐标X and 人物坐标Y then
				local 向量X = 目标点X - 人物坐标X
				local 向量Y = 目标点Y - 人物坐标Y
				local 距离 = math.sqrt(向量X^2 + 向量Y^2)
				
				-- 检查是否已经到达目标点
				if 距离 <= 距离目标 then
					print("已到达目标点!")
					if 当前拖动状态 then
						松开轮盘()
						当前拖动状态 = false
					end
					return true
				end
				
				-- 计算移动角度
				local 角度 = math.deg(math.atan2( - 向量Y , 向量X)) -- 注意Y轴方向
				if 角度 < 0 then 角度 = 角度 + 360 end
				
				print("移动到目标点，距离: " .. math.floor(距离) .. " 角度: " .. math.floor(角度))
				
				-- 如果没有在拖动，或者角度变化较大，重新开始拖动
				if not 当前拖动状态 then
					拖动轮盘(角度)
					当前拖动状态 = true
				end
			end
		end
		if 截图 ~= nil and 截图.isRecycled() == false then
			截图.recycle()
		end
		sleep(100) -- 控制检测频率
	end
	
	print("移动完成或超时")
	if 当前拖动状态 then
		松开轮盘()
	end
	扫屏移动()
	return false
end
