			elseif 标签 == "被动技能" then
				-- YOLOv11使用x1,y1,x2,y2格式，计算中心点
				真实X = math.floor((检测项.x1 + 检测项.x2) / 2)
				真实Y = math.floor((检测项.y1 + 检测项.y2) / 2)
				--262,604,398,670  排除范围
				范围内技能 = 真实X >= 281 and 真实X <= 1243 and 真实Y >= 373 and 真实Y <= 695
				if 当前设备类型 == 0 then
					
					if 范围内技能 then
						table.insert(被动技能检测列表 , {x = 真实X , y = 真实Y})
					end
					
				else
					if not (真实X >= 256 and 真实X <= 400 and 真实Y >= 600 and 真实Y <= 672) then
						table.insert(被动技能检测列表 , {x = 真实X , y = 真实Y})
					end
				end
				
			end
			
		end
		if 技能存在 then
			
			if not 判断_副本内疲劳值() and not 判断_副本中() then
				安全释放自动打怪()
				释放检测到的技能(技能列表)
				安全启动自动打怪()
			end
			
		end
		
		if not 判断_副本中() then
			print('不在副本中跳过卡住和打怪操作')
			非战斗卡死开始时间 = nil
			战斗中卡死开始时间 = nil
			上次找到人物时间 = os.time()
			上次人物检测时间 = os.time()
			
			未识别到怪物等级 = os.time()
			goto continue
		end
		if 拾取标签 or 判断_拾取_图色() then
			print("战斗中检测到拾取，执行拾取并重启攻击。")
			安全释放自动打怪()
			随机延时(200 , 400)
			随机点击普通攻击()
			随机延时(200 , 400)
			随机拖动轮盘()
			随机延时(200 , 400)
			安全启动自动打怪()
			goto continue
		end
		
		if 蹲下标签 then
			print("检测到蹲下标签，执行恢复操作。")
			安全释放自动打怪()
			随机点击普通攻击()
			安全启动自动打怪()
			goto continue
		end
		------------------------------------------------------------------------------------------
		---材料距离检测和处理
		----------------------------------------------------------------------------------------
		-- 检测材料与人物的距离，如果在50像素内就执行移动操作再启动自动打怪
		if 材料存在 and 找到人物 and #材料列表 > 0 and not 攻击中标签 then
			for _ , 材料 in ipairs(材料列表) do
				local 距离 = math.sqrt((人物位置.x - 材料.x)^2 + (人物位置.y - 材料.y)^2)
				if 距离 <= 50 then
					print("检测到材料距离人物" .. math.floor(距离) .. "像素，执行移动操作")
					安全释放自动打怪()
					随机移动或拖动轮盘()
					随机延时(100 , 200)
					安全启动自动打怪()
					goto continue
				end
			end
		end
		------------------------------------------------------------------------------------------
		---怪物等级和攻击中相关
		----------------------------------------------------------------------------------------
		-- 检查并释放被动技能
		if 判断_副本中() and not 攻击中标签 and not 判断_怪物等级() and not 怪物存在 then
			
			检查并释放被动技能(被动技能检测列表 , 当前时间 , 攻击中标签)
			
		end
		
		-- 优先处理怪物等级颜色记录（状态记录，不影响战斗流程）
		if 判断_怪物等级() then
			-- 链条对比模式：检测到怪物立即记录颜色，等待0.6秒后再次对比
			local 当前时间 = os.clock()
			local 当前颜色 = getPixelColor(747 , 31)
			
			if 上次记录的颜色 == nil then
				-- 第一次检测到怪物等级，立即记录颜色A（不等待时间间隔）
				上次记录的颜色 = 当前颜色
				上次对比时间 = 当前时间
				print("首次检测到怪物等级，立即记录颜色A: " .. 当前颜色)
				安全启动自动打怪()
			else
				-- 已有记录的颜色，检查是否到达对比时间间隔
				if 当前时间 - 上次对比时间 >= 0.1 then
					-- 时间间隔达到0.6秒，对比颜色
					if 当前颜色 ~= 上次记录的颜色 then
						-- 颜色B与颜色A不同，达到攻击条件
						print("----------检测到颜色变化: A(" .. 上次记录的颜色 .. ") -> B(" .. 当前颜色 .. ")，达成攻击条件----------")
						
						-- 更新记录：B为新A
						上次记录的颜色 = 当前颜色
						上次对比时间 = 当前时间
						print("已记录B为新A: " .. 上次记录的颜色)
						
						-- 然后释放技能
						if 技能列表 and #技能列表 > 0 then
							安全释放自动打怪()
							if not 找到人物 then
								技能_后跳()
								释放检测到的技能(技能列表)
							else
								释放检测到的技能(技能列表)
							end
							
							安全启动自动打怪()
							--goto continue
						end
						非战斗卡死开始时间 = nil
						战斗中卡死开始时间 = nil
						上次找到人物时间 = os.time()
						上次人物检测时间 = os.time()
						未识别到怪物等级 = os.time()
						战斗开始时间 = os. time()
						
					else
						-- 颜色一致，不攻击，更新记录继续打怪
						if 当前时间 - 上次对比时间 >= 5 then
							
							安全释放自动打怪()
							
							-- 根据怪物位置调整方向
							if 怪物存在 and #怪物列表 > 0 and 找到人物 then
								local 目标怪物 = 怪物列表[1]
								if 目标怪物.x < 人物位置.x then
									print("5秒后颜色未变化，怪物在左侧，向左调整")
									调整方向向左()
								else
									print("5秒后颜色未变化，怪物在右侧，向右调整")
									调整方向向右()
								end
							else
								print("5秒后颜色未变化，调整方向重新执行自动打怪: " .. 当前颜色)
							end
							
							安全启动自动打怪()
						end
						上次对比时间 = 当前时间
						安全启动自动打怪()
						
					end
				else
					-- 未到对比时间，继续自动打怪
					安全启动自动打怪()
				end
			end
			
		end
		
		-- 然后处理攻击中标签（战斗响应）
		if 攻击中标签 and not 移动标签 and 技能列表 and #技能列表 > 0 then
			
			print("检测到攻击中标签，优先释放技能反击。")
			安全释放自动打怪()
			if not 找到人物 then
				技能_后跳()
			end
			释放检测到的技能(技能列表)
			安全启动自动打怪()
			
			--goto continue
		end
		
		if os.time() - 未识别到怪物等级 > 4 then
			
			if not 判断_怪物等级() then
				
				安全释放自动打怪()
				
				if not 向左调整 then
					print('未识别到怪物等级超过4秒调整方向向左')
					随机延时(300 , 400)
					调整方向向左()
					向左调整 = true
					向右调整 = false
				elseif not 向右调整 then
					print('未识别到怪物等级超过4秒调整方向向右')
					随机延时(300 , 400)
					调整方向向右()
					向右调整 = true
					向左调整 = false
				end
				
				安全启动自动打怪()
				非战斗卡死开始时间 = nil
				战斗中卡死开始时间 = nil
				上次找到人物时间 = os.time()
				上次人物检测时间 = os.time()
				未识别到怪物等级 = os.time()
				goto continue
			end
			
		end
		
		-------------------------------------------------------------------------
		-------------------------------------------------------------------------
		
		---------------------------------
		-- 3. 角色卡死/丢失逻辑
		---------------------------------
		
		if 找到人物 then
			上次找到人物时间 = os.time()
			if os.time() - 上次人物检测时间 >= 1 then -- 每秒检测一次移动
				local 移动距离 = math.sqrt((人物位置.x - 上次人物坐标.x)^2 + (人物位置.y - 上次人物坐标.y)^2)
				
				if 移动距离 < 20 then -- 如果移动距离很小，视为可能卡住
					local 当前在战斗 = 攻击中标签 --怪物存在 or
					位置有变化 = false
					if not 当前在战斗 then -- 非战斗状态的卡死处理
						-- 检测到战斗状态转换，重置战斗中卡死计时器
						if 战斗中卡死开始时间 ~= nil then
							print("从战斗状态转为非战斗状态，重置战斗中卡死计时器")
							战斗中卡死开始时间 = nil
						end
						
						-- 非战斗卡死计时
						if 非战斗卡死开始时间 == nil then
							非战斗卡死开始时间 = os.time()
						end
						local 非战斗卡住时间 = os.time() - 非战斗卡死开始时间
						
						if 非战斗卡住时间 >= 随机数(8 , 10) then -- 卡住超过8秒
							print("非战斗状态：人物卡住超过8秒，执行脱困操作")
							
							安全释放自动打怪()
							卡图随机移动()
							安全启动自动打怪()
							上次对比时间 = 当前时间
							非战斗卡死开始时间 = nil -- 重置计时器
						elseif 非战斗卡住时间 >= 随机数(4 , 5) then
							print("非战斗状态：人物卡住超过3秒，尝试随机移动或拖动轮盘")
							
							安全释放自动打怪()
							随机移动或拖动轮盘()
							安全启动自动打怪()
							上次对比时间 = 当前时间
						elseif 非战斗卡住时间 >= 0.7 then
							print("非战斗状态：人物卡住超过1秒，尝试重新启动自动打怪")
							
							if not 已启动 and not 判断_已启动自动() and 判断_副本中() then
								print("非战斗状态：人物卡住超过1秒，尝试重新启动自动打怪")
								安全释放自动打怪()
								安全启动自动打怪()
								战斗中卡死开始时间 = nil -- 重置计时器
							end
							
						end
						
					else -- 战斗状态的卡死处理
						-- 检测到非战斗状态转换，重置非战斗卡死计时器
						if 非战斗卡死开始时间 ~= nil then
							print("从非战斗状态转为战斗状态，重置非战斗卡死计时器")
							非战斗卡死开始时间 = nil
						end
						
						-- 战斗中卡死计时
						if 战斗中卡死开始时间 == nil then
							战斗中卡死开始时间 = os.time()
						end
						local 战斗卡住时间 = os.time() - 战斗中卡死开始时间
						
						if 战斗卡住时间 >= 0.7 then
							print("战斗状态：人物卡住超过1秒，尝试重新启动自动打怪")
							安全释放自动打怪()
							安全启动自动打怪()
							上次找到人物时间 = os.time() -- 重置计时器
							战斗中卡死开始时间 = nil -- 重置计时器
							
						end
					end
				else
					-- 角色在移动，重置所有卡住计时器
					print('人物正在移动，重置所有未移动计时')
					非战斗卡死开始时间 = nil
					战斗中卡死开始时间 = nil
					上次人物检测时间 = os.time()
					上次找到人物时间 = os.time()
					上次人物坐标 = 人物位置
					位置有变化 = true
				end
			end
			
		else -- 如果没有找到人物
			位置有变化 = false
			if 当前在战斗 then
				
				if os.time() - 上次找到人物时间 >= 随机数(2 , 2.5) then
					print("超过1秒未检测到人物。")
					if 判断_副本中() then
						
						安全释放自动打怪()
						安全启动自动打怪()
						--随机延时(1000 , 1200)
						非战斗卡死开始时间 = nil
						非战斗卡死开始时间 = nil
						战斗中卡死开始时间 = nil
					end
					上次找到人物时间 = os.time() -- 重置计时器
				end
				
			else
				if os.time() - 上次找到人物时间 >= 7 then
					安全释放自动打怪()
					print('7秒没找到人物分钟执行脱困')
					释放检测到的技能(技能列表)
					
					扫屏寻怪()
					安全启动自动打怪()
					非战斗卡死开始时间 = nil
					战斗中卡死开始时间 = nil
					上次找到人物时间 = os.time() -- 重置计时器
					
				end
				
			end
		end
		
		---------------------------------
		-- 4. 战斗决策逻辑
		---------------------------------
		
		if 怪物存在 and 找到人物 and not 移动标签 then
			local 目标怪物 = 怪物列表[1]
			local 距离 = math.sqrt((人物位置.x - 目标怪物.x)^2 + (人物位置.y - 目标怪物.y)^2)
			
			if 距离 <= 200 then -- 在攻击范围内350
				print("进入攻击范围，准备攻击。")
				-- 计算怪物相对于人物的位置
				local 怪物在右边 = 目标怪物.x > 人物位置.x
				local 人物朝向 = 人物位置.朝向 or "人物"
				
				print(string.format("怪物位置: %s, 人物朝向: %s" , 怪物在右边 and "右边" or "左边" , 人物朝向))
				
				-- 根据朝向和怪物位置决策攻击方式
				if 怪物在右边 and 人物朝向 == "人物向右" then
					-- 怪物在右边且人物朝向右边，直接攻击
					
					print("怪物在右边且人物朝向正确，直接释放技能")
					if 技能列表 and #技能列表 > 0 then
						安全释放自动打怪()
						释放检测到的技能(技能列表)
						
						安全启动自动打怪()
						goto continue
					else
						print("无技能可用，继续攻击。")
					end
					
				elseif 怪物在右边 and 人物朝向 == "人物向左" then
					-- 怪物在右边但人物朝向左边，需要调整方向
					
					print("怪物在右边但人物朝向错误，先调整方向")
					-- 调整方向后释放技能
					if 技能列表 and #技能列表 > 0 then
						安全释放自动打怪()
						调整方向向右()
						释放检测到的技能(技能列表)
						安全启动自动打怪()
						goto continue
					end
					
				elseif not 怪物在右边 and 人物朝向 == "人物向左" then
					-- 怪物在左边且人物朝向左边，直接攻击
					
					print("怪物在左边且人物朝向正确，直接释放技能")
					if 技能列表 and #技能列表 > 0 then
						安全释放自动打怪()
						释放检测到的技能(技能列表)
						安全启动自动打怪()
						goto continue
						
					else
						print("无技能可用，继续攻击。")
					end
					
				elseif not 怪物在右边 and 人物朝向 == "人物向右" then
					-- 怪物在左边但人物朝向右边，需要调整方向
					
					print("怪物在左边但人物朝向错误，先调整方向")
					
					-- 调整方向后释放技能
					
					if 技能列表 and #技能列表 > 0 then
						安全释放自动打怪()
						调整方向向左()
						释放检测到的技能(技能列表)
						
						安全启动自动打怪()
						goto continue
					end
					
				else
					-- 人物朝向检测失败，使用默认攻击方式
					print("人物朝向检测失败，使用默认攻击方式")
					
					安全启动自动打怪()
				end
				
			else
				
				安全启动自动打怪()
				正在移动 = true
			end
			
		elseif 怪物存在 and not 找到人物 then
			-- 看不见自己但看得见怪，发动攻击
			
			print("未检测到人物但有怪物，安全启动自动打怪")
			
			安全启动自动打怪()
			
		else
			-- 没有怪物，继续移动探索
			
			安全启动自动打怪()
		end
		
		if not 已启动 and not 判断_已启动自动() and 判断_副本中() then --and not 位置有变化
			安全释放自动打怪()
			安全启动自动打怪()
			
		end
		::continue::
		-- 清理截图
		if 截图 ~= nil and 截图.isRecycled() == false then
			截图.recycle()
		end
		随机延时(80 , 100) -- 主战斗循环间隔
	end
	安全释放自动打怪()
	
	releaseCapture()
end
