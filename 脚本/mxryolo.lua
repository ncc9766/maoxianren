	local 战斗开始时间5分钟 = os.time()
	local 识别到轮盘次数 = 0
	local 检测不到返回城镇时间 = os.time()
	local 上次人物检测时间 = os.time()
	local 上次找到人物时间 = os.time()
	local 未识别到怪物等级 = os.time()
	local 卡返回城镇地图 = 判断_滚石监狱地图()
	
	local 强制开启yolo图 = false
	-- 主战斗循环
	while true do
		-- 将循环内使用的局部变量声明移到循环顶部，以避免 'goto' 跳转错误
		local 截图 , 检测结果 , 解析结果
		local 怪物存在 , 找到人物 , 攻击中标签 , 领主房间标签 , 拾取标签 , 蹲下标签 , 材料存在 , 移动标签 , 已启动 , 技能存在
		local 怪物列表 , 技能列表 , 人物位置 , 被动技能检测列表 , 材料列表
		local 当前时间 = os.time() -- 将当前时间声明移到循环开始，避免goto跳转错误
		
		---------------------------------
		-- 1. 通用高优先级检查
		---------------------------------
		if 检测游戏是否闪退() then
			安全释放自动打怪()
			print("检测到游戏闪退，结束自动刷图。")
			break
			
