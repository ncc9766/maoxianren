	-- 内部状态及控制变量
	local 正在移动 = false -- 标记角色是否正在执行移动或攻击动作
	
	local 领主房间模式 = false -- 标记是否已进入领主房间
	local 觉醒技能已执行 = false -- 在领主房间内，确保觉醒大招只释放一次
	local 觉醒第一段释放时间 = nil -- 记录觉醒第一段释放的时间
