			截图.recycle()
		end
		sleep(100) -- 主战斗循环间隔
		
	end
	安全释放自动打怪()
	
	releaseCapture()
end

function yolo自动捡猫卡()
	if 同步关闭yolo战斗功能() then
		return
	end
	
	print("开始简化拾取系统...")
	local 开始时间 = os.time()
	local 时间限制 = 15
	local 目标点X = 650
	local 目标点Y = 528
	local 移动到指定位置 = false
	local 无物品检测计数 = 0
	local 轮盘已按下 = false
	local 右移轮盘已按下 = false
	local 当前轮盘X , 当前轮盘Y = 0 , 0
	
	local function 释放轮盘()
		if 轮盘已按下 or 右移轮盘已按下 then
			touchUp(0)
			轮盘已按下 = false
			右移轮盘已按下 = false
			随机延时(80 , 100)
		end
	end
	
	local function 持续向右拖动轮盘()
		if 右移轮盘已按下 then
			return
		end
		print("人物X未到拾取位置，持续向右拖动轮盘")
		拖动轮盘(0)
		右移轮盘已按下 = true
	end
	
	local function 获取随机拖动距离()
		return math.random(100 , 120)
	end
	
	local function 滑动拾取材料列表(材料列表)
		if not 材料列表 or #材料列表 == 0 then
			return
		end
		
		释放轮盘()
		local 起点X = 705 + math.random( - 5 , 5)
		local 起点Y = 440 + math.random( - 5 , 5)
		
		touchDown(0 , 起点X , 起点Y)
		sleep(10)
		
		for _ , 材料 in ipairs(材料列表) do
			local 目标X = math.floor(材料.x + math.random( - 5 , 5))
			local 目标Y = math.floor(材料.y + math.random( - 5 , 5))
			print(string.format("滑动拾取%s: %d,%d" , 材料.类型 or "材料" , 目标X , 目标Y))
			touchMoveEx(0 , 目标X , 目标Y , math.random(80 , 120))
		end
		
		touchUp(0)
		sleep(50)
	end
	
	local img , res , tb
	local 人物位置 , 材料列表
	local 需要退出 = false
	
	while os.time() - 开始时间 < 时间限制 do
		img = nil
		
		if 检测游戏是否闪退() or not 判断_猫卡一图() then
			print('检测到游戏闪退，退出yolo自动捡猫卡')
			需要退出 = true
			goto continue
		end
		
		if 判断_拾取_图色() then
			释放轮盘()
			随机点击普通攻击()
			goto continue
		end
		
		if 清屏_系统关闭X() then
			释放轮盘()
			随机延时(300 , 400)
			goto continue
		end
		
		img = LuaEngine.snapShot(0 , 0 , 0 , 0)
		res = Yolov8_640.detect(img , 0.35)
		if res == nil then
			释放轮盘()
			无物品检测计数 = 无物品检测计数 + 1
			if 无物品检测计数 >= 3 then
				需要退出 = true
			end
			goto continue
		end
		
		tb = res
		人物位置 = nil
		材料列表 = {}
		
		for i = 1 , #tb do
			local item = tb[i]
			local 标签 = item.label or "未知"
			local x = math.floor(item.x1)
			local y = math.floor(item.y1)
			local w = math.floor(item.x2 - item.x1)
			local h = math.floor(item.y2 - item.y1)
			local 置信度 = item.prob
			
			if 标签 == "人物向左" or 标签 == "人物向右" then
				人物位置 = {
					x = x + math.floor(w/2) ,
					y = y + h ,
					朝向 = 标签
				}
			elseif 标签 == "猫卡" then
				table.insert(材料列表 , {
					x = x + w/2 ,
					y = y + h ,
					prob = 置信度 ,
					类型 = "猫卡"
				})
			elseif 标签 == "材料" and 置信度 >= 0.2 then
				table.insert(材料列表 , {
					x = x + w/2 ,
					y = y + h ,
					prob = 置信度 ,
					类型 = "材料"
				})
			end
		end
		
		if not 移动到指定位置 then
			if not 人物位置 then
				print("未检测到人物，暂停拖动等待下一帧")
				释放轮盘()
				goto continue
			end
			
			print(string.format("当前人物坐标:%d,%d" , 人物位置.x , 人物位置.y))
			if 人物位置.x < 目标点X then
				--[===[更新轮盘方向(人物位置.x , 人物位置.y , 目标点X , 目标点Y)]===]
				持续向右拖动轮盘()
				goto continue
			else
				释放轮盘()
				快速全屏拾取滑动()
				移动到指定位置 = true
				print("人物X已到拾取位置，开始按材料坐标拾取")
			end
		end
		
		if #材料列表 == 0 then
			无物品检测计数 = 无物品检测计数 + 1
			释放轮盘()
			if 无物品检测计数 >= 3 then
				需要退出 = true
			end
			goto continue
		end
		
		无物品检测计数 = 0
		print("检测到可拾取物，按识别坐标连续滑动拾取")
		滑动拾取材料列表(材料列表)
		
		::continue::
		
		if img ~= nil and img.isRecycled() == false then
			img.recycle()
		end
		
		if 需要退出 then
			break
		end
		sleep(20)
	end
	
	if os.time() - 开始时间 >= 时间限制 then
		print("拾取超时（超过" .. 时间限制 .. "秒），强制退出")
	end
	释放轮盘()
	releaseCapture()
	print("拾取系统结束")
end

function 自动刷图团本()
	
	if 同步关闭yolo战斗功能() then
		return
	end
	print("--- 开始执行自动刷图 ---")
	
	local 正在移动 = false
	local 战斗开始时间 = os.time()
	local 战斗开始时间5分钟 = os.time()
	local 战斗已结束 = false
	
	local 已释放觉醒第一次 = false
	local 已释放觉醒第二次 = false
	local 释放觉醒间隔 = os.time()
	
	local 上次人物坐标 = {x = 0 , y = 0}
	local 上次人物检测时间 = os.time()
	local 上次找到人物时间 = os.time()
	local 非战斗卡死开始时间 = nil
	local 战斗中卡死开始时间 = nil
	local 未识别到怪物等级 = os.time()
	
	local 被动技能列表 = {}
	local 被动技能最小间隔 = 随机数(500 , 600)
	local 被动技能距离阈值 = 40
	
	local 上次记录的颜色 = nil -- 上次记录的怪物等级颜色，形成A->B->新A->新B的链条
	local 上次对比时间 = 0 -- 上次对比颜色的时间戳
	local 检测到继续 = 0
	-- =================================================================================
	-- 内部辅助函数定义
	-- =================================================================================
	
	-- @brief 安全地释放"自动打怪"状态
	local function 安全释放自动打怪()
		if 正在移动 then
			释放自动打怪()
			随机延时(80 , 100)
			正在移动 = false
		end
	end
	
	-- @brief 安全地启动"自动打怪"状态
	local function 安全启动自动打怪()
		
		if not 正在移动 then
			自动打怪()
			正在移动 = true
		end
		
	end
	
	-- @brief 释放被动技能
	local function 释放被动技能(技能X , 技能Y)
		print("释放被动技能，坐标: (" .. 技能X .. ", " .. 技能Y .. ")")
		
		-- 添加防封随机偏移
		local 偏移X = math.random( - 10 , 10)
		local 偏移Y = math.random( - 10 , 10)
		local 实际X = 技能X + 偏移X
		local 实际Y = 技能Y + 偏移Y
		
		-- 按住技能中心点
		touchDown(0 , 实际X , 实际Y)
		随机延时(50 , 80) -- 短暂按住
		
		-- 向上快速拖动释放
		local 拖动距离 = math.random(300 , 400)
		local 目标Y = 实际Y - 拖动距离
		touchMove(0 , 实际X , 目标Y)
		随机延时(200 , 300) -- 拖动时间
		
		-- 释放
		touchUp(0)
		随机延时(400 , 600)
		
	end
	
	-- @brief 检查被动技能是否需要释放
	local function 检查并释放被动技能(被动技能检测列表 , 当前时间 , 攻击中标签)
		if ( 被动技能检测列表 == nil or #被动技能检测列表 == 0 or 攻击中标签 ) and 判断_副本中() then
			return -- 没有被动技能或正在战斗中不释放
		end
		
		for _ , 被动技能 in ipairs(被动技能检测列表) do
			local 技能X = 被动技能.x
			local 技能Y = 被动技能.y
			
			-- 检查是否是新技能或需要释放
			local 需要释放 = false
			local 已存在技能 = nil
			
			-- 查找是否已存在相似位置的技能
			for i , 已记录技能 in ipairs(被动技能列表) do
				local 距离 = math.sqrt((技能X - 已记录技能.x)^2 + (技能Y - 已记录技能.y)^2)
				if 距离 < 被动技能距离阈值 then
					已存在技能 = 已记录技能
					已存在技能.index = i
					break
				end
			end
			
			if 已存在技能 then
				-- 已存在的技能，检查是否到了释放时间
				if 当前时间 - 已存在技能.上次释放时间 >= 被动技能最小间隔 then
					需要释放 = true
				end
			else
				-- 新发现的技能，直接释放
				需要释放 = true
				table.insert(被动技能列表 , {
					x = 技能X ,
					y = 技能Y ,
					上次释放时间 = 当前时间
				})
			end
			
			if 需要释放 then
				-- 释放被动技能前先安全释放自动打怪
				--释放自动打怪()
				安全释放自动打怪()
				随机延时(800 , 1200)
				释放被动技能(技能X , 技能Y)
				随机延时(200 , 250)
				-- 释放被动技能后立即启动自动打怪
				
				安全启动自动打怪()
				
				--自动打怪()
				-- 更新释放时间
				if 已存在技能 then
					被动技能列表[已存在技能.index].上次释放时间 = 当前时间
				end
			end
		end
	end
	
	-- =================================================================================
	-- 主逻辑开始
	-- =================================================================================
	
	while true do
		
		-- 将循环内使用的局部变量声明移到循环顶部，以避免 'goto' 跳转错误
		local 截图 , 检测结果 , 解析结果
		local 怪物存在 , 找到人物 , 攻击中标签 , 领主房间标签 , 拾取标签 , 蹲下标签 , 材料存在 , 移动标签
		local 怪物列表 , 技能列表 , 人物位置 , 被动技能检测列表
		local 当前时间 = os.time() -- 将当前时间声明移到循环开始，避免goto跳转错误
