					--goto continue
				end
			end
		end
		
		-- 优先处理怪物等级颜色记录（状态记录，不影响战斗流程）
		if 判断_怪物等级() then
			-- 链条对比模式：检测到怪物立即记录颜色，等待0.6秒后再次对比
			local 当前时间 = os.clock()
			--原747 , 31
			--新439,31
			local 当前颜色 = getPixelColor(747 , 31)
			
			if 上次记录的颜色 == nil then
				-- 第一次检测到怪物等级，立即记录颜色A（不等待时间间隔）
				上次记录的颜色 = 当前颜色
				上次对比时间 = 当前时间
				print("首次检测到怪物等级，立即记录颜色A: " .. 当前颜色)
				安全启动自动打怪()
			else
				-- 已有记录的颜色，检查是否到达对比时间间隔
				if 当前时间 - 上次对比时间 >= 0.1 then
					-- 时间间隔达到0.6秒，对比颜色
					if 当前颜色 ~= 上次记录的颜色 then
						-- 颜色B与颜色A不同，达到攻击条件
						print("-----------------------------------检测到颜色变化: A(" .. 上次记录的颜色 .. ") -> B(" .. 当前颜色 .. ")，达成攻击条件------------------------------")
						
						-- 更新记录：B为新A
						上次记录的颜色 = 当前颜色
						上次对比时间 = 当前时间
						print("已记录B为新A: " .. 上次记录的颜色)
						
						-- 然后释放技能
						if 技能列表 and #技能列表 > 0 then
							安全释放自动打怪()
							if not 找到人物 then
								技能_后跳()
								释放检测到的技能(技能列表)
							else
								释放检测到的技能(技能列表)
							end
							安全启动自动打怪()
							--goto continue
						end
						非战斗卡死开始时间 = nil
						战斗中卡死开始时间 = nil
						上次找到人物时间 = os.time()
						上次人物检测时间 = os.time()
						未识别到怪物等级 = os.time()
						战斗开始时间 = os.time()
						
					else
						-- 颜色一致，不攻击，更新记录继续打怪
						
						--上次对比时间 = 当前时间
						if 当前时间 - 上次对比时间 >= 10 then
							print("0.8秒后颜色未变化，重新执行自动打怪: " .. 当前颜色)
							上次对比时间 = 当前时间
							--上次记录的颜色 = 当前颜色
							安全释放自动打怪()
							
							安全启动自动打怪()
							
							非战斗卡死开始时间 = nil
							战斗中卡死开始时间 = nil
							未识别到怪物等级 = os.time()
							
							goto continue
						end
						安全启动自动打怪()
					end
				else
					-- 未到对比时间，继续自动打怪
					安全启动自动打怪()
					未识别到怪物等级 = os.time()
					战斗开始时间 = os.time()
				end
			end
			
		end
		
		-- 然后处理攻击中标签（战斗响应）
		if 攻击中标签 and not 移动标签 and 技能列表 and #技能列表 > 0 then
			
			print("检测到攻击中标签，优先释放技能反击。")
			安全释放自动打怪()
			
			if not 找到人物 then
				
				技能_后跳()
			end
			释放检测到的技能(技能列表)
			战斗开始时间 = os.time()
			--goto continue
		end
		
		-------------------------------------------------------------------------
		-------------------------------------------------------------------------
		
		---------------------------------
		-- 3. 角色卡死/丢失逻辑
		---------------------------------
		
		if 找到人物 then
			上次找到人物时间 = os.time()
			if os.time() - 上次人物检测时间 >= 1 then -- 每秒检测一次移动
				local 移动距离 = math.sqrt((人物位置.x - 上次人物坐标.x)^2 + (人物位置.y - 上次人物坐标.y)^2)
				
				if 移动距离 < 20 then -- 如果移动距离很小，视为可能卡住
					local 当前在战斗 = 攻击中标签 --怪物存在 or
					位置有变化 = false
