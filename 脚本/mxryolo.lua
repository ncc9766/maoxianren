function 自动拾取材料()
	
	print('自动捡材料单手模式')
	local 连续无材料计数 = 0
	local 正在移动 = false -- 初始化移动状态
	local 开始时间 = os.time()
	local 首次执行 = false
	
	-- 人物移动检测相关变量
	local 上次人物坐标 = {x = 0 , y = 0}
	local 上次人物检测时间 = os.time()
	local 人物未移动开始时间 = nil
	local 人物移动检测间隔 = 随机数(0.7 , 1) -- 每秒检测一次
	local 人物未移动超时时间 = 随机数(1.5 , 2) -- 5秒未移动触发安全释放
	
	-- 未找到人物检测相关变量
	local 上次找到人物时间 = os.time()
	local 未找到人物超时时间 = 随机数(4 , 5) -- 连续2秒未找到人物触发操作
	
	local 当前疲劳值 = 功能_获取疲劳值()
	
	-- @brief 安全地释放"自动打怪"状态
	local function 安全释放自动打怪()
		if 正在移动 then
			touchUp(0)
			随机延时(50 , 100) -- 确保释放操作完成
			正在移动 = false
		end
	end
	
	-- @brief 安全地启动"自动打怪"状态
	local function 安全启动自动打怪()
		if not 正在移动 then
			自动打怪() -- 调用全局自动打怪函数
			随机延时(50 , 100) -- 确保按下操作完成
			正在移动 = true
			print('已启动自动打怪')
		end
	end
	-- 首次执行特殊处理
	if 判断_拾取_图色() then
		随机点击普通攻击()
	end
	
	if 判断_正在拾取() then
		随机拖动轮盘()
	end
	-- 主循环
	while true do
		-- 将循环内使用的局部变量声明移到循环顶部，以避免 'goto' 跳转错误
		local img , res , tb , 已启动
		local 材料存在 = false
		显示('拾取材料中.........')
		
		-- 高优先级检查
		if 检测游戏是否闪退() then
			print('检测到游戏闪退了,退出')
			安全释放自动打怪()
			break
		end
		
		if not 判断_返回城镇1() then
			print("不在返回城镇界面，退出")
			安全释放自动打怪()
			break
		end
		
		if 清屏_学技能提示X() then
			安全释放自动打怪()
			随机延时(400 , 500)
			goto continue
		end
		
		if os.time() - 开始时间 >= 随机数(15 , 20) then
			print('单手拾取系统超时退出')
			安全释放自动打怪()
			break
		end
		
		-- 截图检测
		img = LuaEngine.snapShot(0 , 0 , 0 , 0)
		res = Yolov8_640.detect(img , 0.35)
		
		if res ~= nil then
			tb = res -- YOLOv11直接返回表格，不需要JSON解码
			local 材料存在 = false -- 每次循环重置材料检测状态
			local 人物位置 = nil -- 存储当前人物位置
			
			-- 解析检测结果
			
			for i = 1 , #tb do
				local item = tb[i]
				local 标签 = item.label or "未知" -- YOLOv11直接返回标签字符串
				
				if 标签 == "材料" or 标签 == "猫卡" then
					材料存在 = true
					显示('还有材料未拾取.............')
					
				elseif 标签 == "人物向左" or 标签 == "人物向右" then
					-- 计算人物底部中心点坐标 (YOLOv11使用x1,y1,x2,y2格式)
					local 中心X = math.floor((item.x1 + item.x2) / 2)
					local 底部Y = math.floor(item.y2)
					人物位置 = {
						x = 中心X ,
						y = 底部Y
					}
				elseif 标签 == "已启动" then
					已启动 = true
				end
			end
			
			-- 检测人物移动状态
			if 人物位置 then
				local 当前时间 = os.time()
				上次找到人物时间 = 当前时间 -- 更新找到人物的时间
				
				-- 每秒检测一次人物移动
				if 当前时间 - 上次人物检测时间 >= 人物移动检测间隔 then
					local 移动距离 = math.sqrt((人物位置.x - 上次人物坐标.x)^2 + (人物位置.y - 上次人物坐标.y)^2)
					
					if 移动距离 < 20 then -- 移动距离小于25像素认为未移动
						if 人物未移动开始时间 == nil then
							人物未移动开始时间 = 当前时间
						else
							local 未移动时间 = 当前时间 - 人物未移动开始时间
							if 未移动时间 >= 人物未移动超时时间 then
								print("人物未移动超过" .. 人物未移动超时时间 .. "秒，安全释放自动打怪")
								安全释放自动打怪()
								随机延时(200 , 300)
								随机移动或拖动轮盘()
								-- 重置计时器
								人物未移动开始时间 = nil
							end
						end
					else
						-- 人物在移动，重置未移动计时器
						if 人物未移动开始时间 ~= nil then
							print("人物开始移动，重置未移动计时器")
							人物未移动开始时间 = nil
						end
					end
					
					-- 更新人物坐标和检测时间
					上次人物坐标 = 人物位置
					上次人物检测时间 = 当前时间
				end
			else
				-- 未检测到人物，检查是否超过2秒未找到人物
				local 当前时间 = os.time()
				if 当前时间 - 上次找到人物时间 >= 未找到人物超时时间 then
					print("连续" .. 未找到人物超时时间 .. "秒未找到人物，安全释放自动打怪并执行随机移动")
					安全释放自动打怪()
					随机延时(200 , 300)
					随机移动或拖动轮盘()
					上次找到人物时间 = 当前时间 -- 重置计时器，避免频繁触发
				end
				
				-- 重置未移动计时器
				if 人物未移动开始时间 ~= nil then
					print("未检测到人物，重置未移动计时器")
					人物未移动开始时间 = nil
				end
			end
			
			if 判断_拾取_图色() then
				print('识别到拾取图色执行点击和拖动轮盘')
				安全释放自动打怪()
				随机点击普通攻击()
				随机延时(400 , 600)
				安全启动自动打怪()
				上次找到人物时间 = os.time()
				开始时间 = os.time()
				goto continue
			end
			if not 判断_正在拾取() and not 材料存在 then
				安全释放自动打怪()
				break
			end
			-- 材料存在时，确保自动打怪是启动的
			if 材料存在 or 判断_正在拾取() then
				print('---------找到材料了，确保自动打怪已启动------')
				--安全启动自动打怪() -- 重新启动
				
				if not 已启动 and not 判断_已启动自动() then
					安全释放自动打怪()
					
					安全启动自动打怪()
					
				else
					安全启动自动打怪()
					
				end
				
			end
		end
		::continue::
		-- 清理截图
		print('自动捡材料功能执行中')
		if img ~= nil and img.isRecycled() == false then
			
			img.recycle()
		end
		sleep(200)
	end
	安全释放自动打怪()
	releaseCapture()
	print('自动捡材料单手模式结束')
end

