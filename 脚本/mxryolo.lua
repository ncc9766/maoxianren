				if 怪物在右边 and 人物朝向 == "人物向右" then
					-- 怪物在右边且人物朝向右边，直接攻击
					print("怪物在右边且人物朝向正确，直接释放技能")
					if 技能列表 and #技能列表 > 0 then
						安全释放自动打怪()
						释放检测到的技能(技能列表)
					else
						安全释放自动打怪()
						随机点击普通攻击()
					end
					goto continue
				elseif 怪物在右边 and 人物朝向 == "人物向左" then
					-- 怪物在右边但人物朝向左边，需要调整方向
					print("怪物在右边但人物朝向错误，先调整方向")
					-- 调整方向后释放技能
					if 技能列表 and #技能列表 > 0 then
						安全释放自动打怪()
						调整方向向右()
						释放检测到的技能(技能列表)
					else
						安全释放自动打怪()
						调整方向向右()
						随机点击普通攻击()
					end
					goto continue
				elseif not 怪物在右边 and 人物朝向 == "人物向左" then
					-- 怪物在左边且人物朝向左边，直接攻击
					print("怪物在左边且人物朝向正确，直接释放技能")
					if 技能列表 and #技能列表 > 0 then
						安全释放自动打怪()
						释放检测到的技能(技能列表)
					else
						安全释放自动打怪()
						随机点击普通攻击()
					end
					goto continue
				elseif not 怪物在右边 and 人物朝向 == "人物向右" then
					-- 怪物在左边但人物朝向右边，需要调整方向
					print("怪物在左边但人物朝向错误，先调整方向")
					-- 调整方向后释放技能
					if 技能列表 and #技能列表 > 0 then
						安全释放自动打怪()
						调整方向向左()
						释放检测到的技能(技能列表)
