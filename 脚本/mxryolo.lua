						上次人物检测时间 = os.time()
						未识别到怪物等级 = os.time()
						战斗开始时间 = os. time()
						战斗开始时间5分钟 = os.time()
						
					else
						-- 颜色一致，不攻击，更新记录继续打怪
						if 当前时间 - 上次对比时间 >= 7 then
							上次对比时间 = 当前时间
							--上次记录的颜色 = 当前颜色
							安全释放自动打怪()
							print("7秒后颜色未变化，重新执行自动打怪: " .. 当前颜色)
							安全启动自动打怪()
							
							--goto continue
						end
						安全启动自动打怪()
						
					end
				else
					-- 未到对比时间，继续自动打怪
					安全启动自动打怪()
				end
			end
			
		end
		if os.time() - 未识别到怪物等级 > 8 then
			
			if not 判断_怪物等级() then
				print('未识别到怪物等级超过10秒')
				安全释放自动打怪()
				
				释放检测到的技能(技能列表)
				战斗开始时间 = os.time()
				随机移动或拖动轮盘()
				
				安全启动自动打怪()
				非战斗卡死开始时间 = nil
				战斗中卡死开始时间 = nil
				上次找到人物时间 = os.time()
				上次人物检测时间 = os.time()
				未识别到怪物等级 = os.time()
			end
			
		end
		-- 然后处理攻击中标签（战斗响应）
		if 攻击中标签 and not 移动标签 and 技能列表 and #技能列表 > 0 then
			
			print("检测到攻击中标签，优先释放技能反击。")
			安全释放自动打怪()
