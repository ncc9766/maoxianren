				print("连续两次未检测到副本结束，启动自动打怪")
				
				安全启动自动打怪()
				正在移动 = true
				连续未检测到副本结束计数 = 0
				
				--goto continue
			end
			
		end
		
		---------------------------------
		-- 7. 战斗决策逻辑（不做改变）
		---------------------------------
		if 副本已结束 then
			--显示("一图打完了")
			安全释放自动打怪()
			break
			
		elseif 攻击中标签 then
			连续未检测到副本结束计数 = 0
			--print("检测到攻击中标签，优先释放技能反击。")
			if 技能列表 and #技能列表 > 0 then
				安全释放自动打怪()
				释放检测到的技能(技能列表)
			else
				--print("无技能可用，继续攻击。")
				安全释放自动打怪()
				随机点击普通攻击()
				--安全启动自动打怪()
			end
			goto continue
			
		elseif 怪物存在 and 找到人物 then
			
			local 目标怪物 = 怪物列表[1]
			local 距离 = math.sqrt((人物位置.x - 目标怪物.x)^2 + (人物位置.y - 目标怪物.y)^2)
			
