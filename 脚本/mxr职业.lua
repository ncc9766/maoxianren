function 判断_技能_二值化(当前职业)
	setDict(0 , "职业.txt")
	useDict(0)
	
	-- 如果没有传入职业，重新识别
	if not 当前职业 then
		当前职业 = 判断_识别到的职业简化()
	end
	
	-- 如果仍然无法识别职业，返回false
	if not 当前职业 then
		print("无法识别当前职业，无法进行技能识别")
		return false
	end
	
	-- 获取当前职业对应的技能列表
	local 技能列表 = 职业技能映射[当前职业]
	if not 技能列表 then
		print("未找到职业 " .. 当前职业 .. " 对应的技能配置")
		return false
	end
	
	print("当前职业: " .. 当前职业 .. ", 开始识别相关技能...")
	
	-- 最多尝试7次
	for i = 1 , 7 do
		-- 遍历当前职业的所有技能
		for j , 技能名 in ipairs(技能列表) do
			-- 获取技能颜色配置
			local 颜色配置 = 技能颜色配置[技能名]
			if not 颜色配置 then
				print("错误：技能 " .. 技能名 .. " 没有配置颜色特征")
				return false
			end

			-- 判断颜色配置是字符串还是数组
			local 颜色列表 = type(颜色配置) == "table" and 颜色配置 or {颜色配置}

			-- 尝试所有颜色特征
			for k , 单个颜色配置 in ipairs(颜色列表) do
				local ret , x , y = findStr(33,153,780,708 , 技能名 , 单个颜色配置 , 0.8 , 10 , 10)
				if x ~= - 1 and y ~= - 1 then
					print('找到 ' .. 技能名 .. ' 技能了 (职业: ' .. 当前职业 .. ', 特征' .. k .. ')')

					if j == 1 then
						X = x + 20
						Y = y + 20
						按下点击(X , Y)
					else
						_G["X" .. j] = x + 20
						_G["Y" .. j] = y + 20
						按下点击(_G["X" .. j] , _G["Y" .. j])
					end
					return true
				end
			end
		end
		sleep(100)
	end
	
	return false
end

function 功能_自动配置技能()--自动设置技能
	
	初始化城镇界面()
	local 总运行时间 = os.time()
	local 判断职业 = false
	
	local 首次等待 = false
	while true do
		if os.time() - 总运行时间 > 60 then
			
			return
			
		end
		随机延时(500 , 600)
		if 判断_城镇界面() then
			
			if not 判断_技能_入口() then
				
				if not 判断_角色_入口() then
					显示('未找到角色入口')
					return
				end
				sleep(500)
			end
			
		elseif 判断_技能加点界面() then
			随机延时(400 , 500)
			
			当前角色职业 = 判断_识别到的职业简化()
			if 当前角色职业 then
				
				按下点击({708 , 74 , 807 , 102})--技能配置
				判断职业 = true
			else
				显示('未识别到当前职业')
				清屏(true)
				return
			end
			
		elseif 判断_技能配置地下城() then
			
			if not 首次等待 then
				随机延时(1500 , 1800)
				首次等待 = true
			end
			
			if 判断_技能_二值化(当前角色职业)then
				
				随机延时(300 , 400)
				按下点击({1175 , 134 , 1209 , 170})--技能11
				初始化城镇界面()
				
				return
				
			else
				--显示('未找到'..当前角色职业..'技能')
				if 判断_划到最底部了() then
					初始化城镇界面()
					return
				else
					滑动(691 , 636 , 679 , 179 , 1 , 1 , {15 , 25} , {800 , 1000} , {400 , 500})
					随机延时(700 , 800)
				end
				
			end
		else
			清屏(true)
			
		end
		
	end
	
end
