	useDict(0)
	for i = 1 , 20 , 1 do
		
		local str = ocr(417 , 529 , 839 , 696 , "ffff94-303030|ffdb00-303030|ffff29-303030" , 0.8 , 10 , 10)
		if str~= nil then
			print('当前职业:'..str)
